"""Generate research/results_v2.md FROM results/v2/tables (no hand-typed numbers).
Run after the other v2 scripts: python scripts/v2/make_results_v2.py"""

from __future__ import annotations

import json

import pandas as pd

from collars.v2.common import PREREG, ROOT, SEEN, TABLES
from qcore.splits import file_hash


def J(n):
    return json.loads((TABLES / n).read_text())


def ci(d, k="sharpe"):
    return f"{d[k]:.2f} [{d['lo']:.2f}, {d['hi']:.2f}]"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(out)


def verdict(b: bool) -> str:
    return "SUPPORTED" if b else "NOT SUPPORTED"


def main() -> None:
    h1, h2, h3 = J("h1_vol.json"), J("h2_family.json"), J("h3_hawkes.json")
    pc, cf = J("pricing_checks.json"), J("conformal_nport.json")
    hs = pd.read_csv(TABLES / "haircut_stress.csv")
    fwd_p = ROOT / "results" / "v2" / "forward" / "forward.csv"
    fwd = pd.read_csv(fwd_p) if fwd_p.exists() else pd.DataFrame(columns=["date", "book", "net_return"])
    v, s = h1["validation"], h1["seen_period"]
    d3 = h3["down_events"]["multivariate"]
    ch, ql = pc["chain"], pc["quantlib_max_abs_error"]
    o = []
    A = o.append
    A("# P2 v2 results: Collars Under the Microscope, buy-side upgrade")
    A("")
    A(f"Generated by `scripts/v2/make_results_v2.py` from `results/v2/tables/*`. Pre-registration v2 hash `{file_hash(PREREG)}` "
      "(frozen before any v2 test). v1 results are unchanged. Reset-day timing luck in costless put-spread collars is already "
      "published (Braun, Hoffstein, Israelov, Nze Ndong 2023, see `evidence_v2.md` S1); this is a free-data replication with extensions.")
    A("")
    A("**Timing.** Strikes, fills and every signal are set at the 16:00 close of the reset day from data up to that close and held to the next "
      "reset. **Costs.** v1 half-spread paid on every leg at each reset; no commissions, no market impact; capacity is not modelled "
      "(descriptive scale check only). Sharpe ratios carry 95% stationary-bootstrap CIs and day counts. "
      f"Every table that includes dates after 2019 is labelled `{SEEN}`. Research, not investment advice.")
    A("")
    A("## Verdicts")
    A("")
    A(md(pd.DataFrame([
        ["H1 GJR-GARCH beats VIX3M as the vol input", verdict(h1["H1_supported"]),
         f"VIX3M minus GARCH QLIKE {v['vix3m_minus_garch']['mean']:.3f} [{v['vix3m_minus_garch']['lo']:.3f}, {v['vix3m_minus_garch']['hi']:.3f}] (negative = VIX3M better), n = {v['n_origins']} origins"],
        ["H2 best phase/ladder in the family is overfit", verdict(h2["H2_supported"]),
         f"PBO {h2['pbo']:.3f} (needs > 0.5); deflated Sharpe of best {h2['dsr_best']:.3f} (needs < 0.90)"],
        ["H3 past Hawkes intensity at reset predicts collar-minus-benchmark return", verdict(h3["H3_supported"]),
         f"coef {d3['coef']['lam']:.3f}, Newey-West t {d3['t']['lam']:.2f} (needs > 2), {h3['n_unique_d0']} reset dates"],
    ], columns=["Hypothesis", "Verdict", "Key number"])))
    A("")
    A("All three primary hypotheses are NOT supported. Reported plainly: the VIX-based input is better than a GARCH input, "
      "the phase/ladder family is not shown to be overfit on this window, and reset-day crash clustering does not explain the "
      "collar's relative quarterly return.")
    A("")
    A("## H1: vol input (GJR-GARCH vs VIX3M)")
    A("")
    A(f"Forecast at close t of the mean squared return over t+1..t+63. Scales fitted on development ({h1['n_dev']} origins). "
      f"Evaluation: {h1['validation_period']}.")
    A("")
    rows = []
    for lab, e in (("validation 2017-2019", v), (f"2020-2026 {SEEN}", s)):
        q = e["mean_qlike"]
        rows.append([lab, e["n_origins"], f"{q['A']:.3f}", f"{q['B']:.3f}", f"{q['G']:.3f}",
                     f"{e['vix3m_minus_garch']['mean']:.3f} [{e['vix3m_minus_garch']['lo']:.3f}, {e['vix3m_minus_garch']['hi']:.3f}]",
                     f"{e['vix_minus_garch']['mean']:.3f} [{e['vix_minus_garch']['lo']:.3f}, {e['vix_minus_garch']['hi']:.3f}]"])
    A(md(pd.DataFrame(rows, columns=["Window", "Origins", "QLIKE VIX3M", "QLIKE VIX", "QLIKE GARCH", "VIX3M - GARCH [95% CI]", "VIX - GARCH [95% CI]"])))
    A("")
    A("## H2: overfitting audit of the 168-collar family")
    A("")
    ci_ = h2["best_sharpe_ci"]
    A(f"Window {h2['window']}, {h2['n_days']} days, {h2['n_resets_per_member']} quarterly resets per member. Family Sharpe median "
      f"{h2['family_sharpe_median']:.2f}, range {h2['family_sharpe_min']:.2f} to {h2['family_sharpe_max']:.2f} (excess of T-bills). "
      f"Best member `{h2['best_member']}`: Sharpe {ci(ci_)} over {ci_['n_days']} days; expected best-of-168 Sharpe under no skill "
      f"{h2['expected_max_sharpe_noise_annual']:.2f}. v1's baseline (phase 0, fixed strikes) Sharpe {h2['v1_baseline_phase0_sharpe']:.2f}, rank "
      f"{h2['v1_baseline_rank']} of {h2['n_members']}. PBO {h2['pbo']:.3f} over {h2['n_combinations']} CSCV splits. "
      "These Sharpes mostly reflect the 2011-2019 equity bull market that all members share; they say nothing about out-of-sample skill.")
    A("")
    A("## H3: Hawkes clustering around resets")
    A("")
    rows = []
    for k in ("down_events", "both_sided_events"):
        m_ = h3[k]["multivariate"]
        rows.append([k, h3[k]["n_events_total"], f"{h3[k]['mean_intensity']:.4f}", f"{m_['coef']['lam']:.3f}", f"{m_['t']['lam']:.2f}",
                     f"{h3[k]['univariate']['t']['lam']:.2f}", m_["n"]])
    A(md(pd.DataFrame(rows, columns=["Events", "n events 1990-2019", "mean intensity", "coef (with 63d vol)", "NW t", "NW t (alone)", "n dates"])))
    A("")
    A(f"y = collar quarterly return minus beta-matched benchmark, mean {h3['mean_y_per_quarter']*100:.2f}% per quarter (sd {h3['sd_y']*100:.2f}%). "
      "Newey-West 63 lags because quarters overlap. Phases are shifted copies of one strategy, so the effective sample is far smaller than the pair count.")
    A("")
    A("## Descriptive: pricing realism")
    A("")
    A(f"- **QuantLib cross-check** (AnalyticEuropeanEngine, {ql['n']} random options): max abs error price {ql['price']:.1e}, delta {ql['delta']:.1e}, "
      f"gamma {ql['gamma']:.1e}, vega {ql['vega']:.1e}. The Black-76 pricer agrees to machine precision.")
    A(f"- **Bid-ask half-spread** measured on the real Cboe chain ({ch['as_of']}, expiry {ch['expiry']}, {ch['n_options_used']} OTM options at 78-110% moneyness): "
      f"median {ch['h_chain_median_volpts']:.3f} vol pts (put wing {ch['h_chain_put_wing_median_volpts']:.3f}, call wing {ch['h_chain_call_wing_median_volpts']:.3f}). "
      f"v1's fitted h is {ch['h_v1_volpts']:.3f} vol pts, so v1 is about {ch['h_v1_volpts']/ch['h_chain_median_volpts']:.0f}x the quoted spread: conservative for small size, not a statement about block trades.")
    A(f"- **SVI vs frozen surface** on that one snapshot: SVI RMSE {ch['svi_rmse_volpts']:.2f} vol pts (rho hit its bound, so treat as an upper-quality fit only), "
      f"frozen VIX-based surface RMSE {ch['frozen_surface_rmse_volpts']:.2f}, bias {ch['frozen_surface_bias_volpts']:.2f}. "
      "The historical surface stays VIX-term-structure based because free data have no historical chains.")
    oi = ch["capacity_chain_open_interest"]
    A(f"- **Capacity scale check**: the latest N-PORT ({ch['capacity_nport_period']}) shows {ch['capacity_fund_contracts_per_leg_latest_n_port']:.0f} contracts per leg; "
      f"open interest in the 3 nearest strikes of the 2026-12-31 chain is {oi['long_put_K1']['open_interest_sum_3']:.0f} (K1), {oi['short_put_K2']['open_interest_sum_3']:.0f} (K2), "
      f"{oi['short_call_Kc']['open_interest_sum_3']:.0f} (Kc). One snapshot, a different expiry, quoted OI only: the fund's size is large relative to listed OI at the put strikes; "
      "capacity of an outside copy is not estimated here.")
    A("")
    A("### Bid-ask haircut stress (every option trade; fixed 95/80 strikes)")
    A("")
    t = hs.copy()
    t["h (vol pts)"] = t["h_volpts"].map(lambda x: f"{x:.3f}")
    t["ann return"] = (t["ann_return"] * 100).map(lambda x: f"{x:.2f}%")
    t["cost drag vs h=0"] = t["cost_drag_vs_zero_pct"].map(lambda x: f"{x:.2f} pp")
    t["Sharpe [95% CI]"] = t.apply(lambda r: f"{r['sharpe']:.2f} [{r['lo']:.2f}, {r['hi']:.2f}]", axis=1)
    A(md(t[["window", "book", "h_name", "h (vol pts)", "ann return", "cost drag vs h=0", "Sharpe [95% CI]", "n_days"]]))
    A("")
    dd = pc["phase_dispersion_dev_val"]
    A(f"Across all 63 phases (dev+val): std of annualised return {dd['v1_h']['std_ann_return_pct']:.2f} pp, range {dd['v1_h']['min_pct']:.2f}% to {dd['v1_h']['max_pct']:.2f}% at v1 h; "
      f"at 2x v1 h std {dd['2x_v1_h']['std_ann_return_pct']:.2f} pp, range {dd['2x_v1_h']['min_pct']:.2f}% to {dd['2x_v1_h']['max_pct']:.2f}%. Costs shift the level; they do not shrink the phase spread. "
      "Not modelled: commissions, market impact, the fund's actual execution.")
    A("")
    A("## Descriptive: conformal intervals on pricer error vs N-PORT")
    A("")
    rows = []
    for f, e in cf["funds"].items():
        rows.append([f, e["n_quarters"], e["n_scored"], f"{e['coverage']:.2f} [{e['coverage_95ci'][0]:.2f}, {e['coverage_95ci'][1]:.2f}]",
                     f"{e['mean_error_pp']:.2f}", f"{e['mae_pp']:.2f}", f"{e['mean_interval_width_pp']:.2f}"])
    p_ = cf["pooled"]
    rows.append(["pooled", "", p_["n_scored"], f"{p_['coverage']:.2f} [{p_['coverage_95ci'][0]:.2f}, {p_['coverage_95ci'][1]:.2f}]", "", "", ""])
    A(md(pd.DataFrame(rows, columns=["Fund", "Quarters", "Scored", "Coverage (nominal 0.90) [95% CI]", "Mean error pp", "MAE pp", "Mean width pp"])))
    A("")
    A(f"All quarters are in the {SEEN}. {cf['note']}")
    A("")
    A("## Forward tracking")
    A("")
    if len(fwd):
        g = fwd.groupby("book")["net_return"].agg(["count", lambda x: (1 + x).prod() - 1]).reset_index()
        g.columns = ["book", "days", "cumulative return"]
        g["cumulative return"] = (g["cumulative return"] * 100).map(lambda x: f"{x:.2f}%")
        A(f"{fwd['date'].nunique()} forward days logged (first {fwd['date'].min()}, last {fwd['date'].max()}). Far too short to read: earliest read 2027-11.")
        A("")
        A(md(g))
    else:
        A("No forward days logged yet.")
    A("")
    (ROOT / "research" / "results_v2.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print("wrote research/results_v2.md")


if __name__ == "__main__":
    main()
